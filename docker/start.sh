#!/bin/bash

# ============================================
# سكريبت بدء تشغيل Laravel على Render
# ============================================

echo "🚀 بدء تشغيل تطبيق الفلكلور..."

# 1. انتظار قصير حتى تصبح قاعدة البيانات جاهزة
echo "⏳ انتظار قاعدة البيانات..."
sleep 5

# 2. تشغيل الهجرات (تحديث الجداول)
echo "📦 تشغيل الهجرات..."
php artisan migrate --force

# 3. تشغيل البذور (إنشاء المستخدمين والتصنيفات)
echo "🌱 تشغيل البذور..."
php artisan db:seed --force

# 4. إعادة تعيين كاش الصلاحيات
echo "🔐 إعادة تعيين كاش الصلاحيات..."
php artisan permission:cache-reset

# 5. تحسين الأداء (تخزين الإعدادات والمسارات)
echo "⚡ تحسين الأداء..."
php artisan config:cache
php artisan route:cache
php artisan view:cache

# 6. إنشاء رابط التخزين (للملفات المحلية إن وُجدت)
echo "🔗 إنشاء رابط التخزين..."
php artisan storage:link

echo "✅ اكتمل الإعداد بنجاح!"

# ============================================
# تشغيل الخدمات
# ============================================

echo "🌐 تشغيل Nginx..."
service nginx start

echo "🐘 تشغيل PHP-FPM..."
# ✅ تشغيل PHP-FPM في المقدمة (foreground) ليبقى الحاوية نشطاً
php-fpm -F